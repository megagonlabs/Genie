"""Task Execution Flow and State Management.

This module provides the TaskFlowManager, which orchestrates the state lifecycle
of complex, multi-agent tasks structured as Directed Acyclic Graphs (DAGs).
It tracks global objectives, isolates individual sub-task contexts, and resolves
execution dependencies to determine which workloads are unblocked and ready to run.
"""

from typing import Optional, List, Dict, Any
from storages.interface import BaseMemoryStorage
from models.memory import MemoryItem, MemoryScope
from models.task import TaskState, SubTaskState, TaskStatus


class TaskStateError(Exception):
    """Base exception for all task flow management errors."""

    pass


class TaskNotFoundError(TaskStateError):
    """Raised when a requested task ID does not exist in the storage layer."""

    pass


class TaskFlowManager:
    """Manages serialization, retrieval, and dependency resolution for agentic tasks.

    This class acts as the "State Machine" for the workflow. It reads and writes
    the execution graph to the persistent storage layer, ensuring that agents can
    safely crash or pause, and the system will know exactly where to resume.
    """

    def __init__(self, storage: BaseMemoryStorage):
        """Initializes the Task Flow Manager.

        Parameters:
            storage: The underlying database/memory storage where the state
                     JSON will be persisted.
        """
        self.storage = storage

    def _get_state_memory_item(self, task_id: str) -> Optional[MemoryItem]:
        """Low-level helper to fetch the raw MemoryItem from storage."""
        return self.storage.get(memory_id=task_id)

    def save_state(self, state: TaskState) -> None:
        """Serializes and saves (or updates) the complete TaskState in storage.

        Parameters:
            state: The fully populated TaskState object to persist.
        """
        existing_item = self._get_state_memory_item(state.task_id)
        state_dict = state.model_dump(mode="json")

        if existing_item:
            # If the state already exists, update it in place
            self.storage.update(memory_id=state.task_id, new_content=state_dict)
        else:
            # For new states, save with a specific metadata tag.
            # This tag ("task_operational_state") tells the underlying storage engine
            # NOT to generate vector embeddings for this mechanical JSON data.
            state_memory = MemoryItem(id=state.task_id, scope=MemoryScope.SESSION, content=state_dict, metadata={"type": "task_operational_state"})
            self.storage.save(state_memory)

    def load_state(self, task_id: str) -> Optional[TaskState]:
        """Loads and deserializes a TaskState from storage.

        Parameters:
            task_id: The unique identifier of the global workflow.

        Returns:
            The hydrated TaskState Pydantic object, or None if not found.

        Raises:
            ValueError: If the underlying JSON data is corrupt or fails schema validation.
        """
        memory_item = self._get_state_memory_item(task_id)
        if not memory_item:
            return None

        try:
            return TaskState.model_validate(memory_item.content)
        except Exception as e:
            raise ValueError(f"Corrupt state data encountered for task {task_id}") from e

    def add_sub_task(self, task_id: str, sub_task: SubTaskState) -> TaskState:
        """Injects a newly planned sub-task into the execution tree.

        Parameters:
            task_id: The global task to attach this sub-task to.
            sub_task: The newly created SubTaskState.

        Returns:
            The updated global TaskState.

        Raises:
            TaskNotFoundError: If the parent task_id does not exist.
        """
        state = self.load_state(task_id)
        if not state:
            raise TaskNotFoundError(f"Cannot add sub-task. Parent Task '{task_id}' not found.")

        state.sub_tasks.append(sub_task)
        self.save_state(state)
        return state

    def update_sub_task_status(self, task_id: str, sub_task_id: str, status: TaskStatus, outputs: Optional[Dict[str, Any]] = None, error: Optional[str] = None) -> TaskState:
        """Updates the status, outputs, and error tracking of a specific sub-task.

        This method automatically evaluates the global task to see if the entire
        DAG (Directed Acyclic Graph) has concluded based on this specific update.

        Parameters:
            task_id: The global workflow ID.
            sub_task_id: The specific step ID being updated.
            status: The new state (e.g., COMPLETED, FAILED).
            outputs: Optional dictionary of data generated by the agent.
            error: Optional traceback or error string if the agent failed.

        Returns:
            The updated global TaskState.

        Raises:
            TaskNotFoundError: If the parent task_id does not exist.
        """
        state = self.load_state(task_id)
        if not state:
            raise TaskNotFoundError(f"Cannot update sub-task. Global Task '{task_id}' not found.")

        # Find and update the specific sub-task
        for st in state.sub_tasks:
            if st.sub_task_id == sub_task_id:
                st.status = status
                st.outputs = outputs if outputs else {}
                st.error = error
                break

        # --- Automated Global Status Evaluation ---
        if status == TaskStatus.FAILED:
            # If any single agent fails, halt the entire workflow
            state.status = TaskStatus.FAILED
        else:
            # Check if all sub-tasks in the DAG are now marked as completed
            all_done = all(st.status == TaskStatus.COMPLETED for st in state.sub_tasks)
            if all_done and len(state.sub_tasks) > 0:
                state.status = TaskStatus.COMPLETED

        self.save_state(state)
        return state

    def get_runnable_sub_tasks(self, task_id: str) -> List[SubTaskState]:
        """Resolves DAG dependencies and returns all unblocked, executable sub-tasks.

        This is the core engine function that determines "What can run right now?".
        It looks at all pending tasks and checks if their listed dependencies
        have successfully finished.

        Parameters:
            task_id: The global workflow ID to evaluate.

        Returns:
            A list of SubTaskStates that are ready to be picked up by agents.
        """
        state = self.load_state(task_id)
        if not state:
            return []

        # Gather a set of all sub_task_ids that have successfully finished
        completed_ids = {st.sub_task_id for st in state.sub_tasks if st.status == TaskStatus.COMPLETED}

        runnable = []
        for st in state.sub_tasks:
            if st.status == TaskStatus.PENDING:
                # A task is unblocked if ALL of its required dependencies are in the completed set
                if all(dep in completed_ids for dep in st.dependencies):
                    runnable.append(st)

        return runnable

    def clear_state(self, task_id: str) -> None:
        """Removes the entire task operational state from persistent storage."""
        if self._get_state_memory_item(task_id):
            self.storage.delete(memory_id=task_id)
