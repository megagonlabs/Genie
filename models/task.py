"""Task and Workflow State Schema Definitions.

This module provides the Pydantic data models used to represent the lifecycle
and structure of multi-agent workflows. It models the overarching global task
as well as the individual sub-tasks that make up the Directed Acyclic Graph (DAG),
allowing the TaskFlowManager to pause, resume, and track execution state.
"""

from pydantic import BaseModel, Field
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone
from enum import Enum
import uuid


class TaskStatus(str, Enum):
    """Enumeration of all possible lifecycle states for a task or sub-task."""

    PENDING = "pending"
    """The task is queued but blocked by unfinished dependencies."""

    RUNNING = "running"
    """The task is currently being executed by an agent."""

    COMPLETED = "completed"
    """The task finished successfully and its outputs are ready for downstream consumption."""

    FAILED = "failed"
    """The task encountered an unrecoverable error and execution was halted."""


class SubTaskState(BaseModel):
    """Represents a single, discrete unit of work (a node) within the execution graph.

    Agents receive this state, consume its 'inputs', execute their logic, and
    populate the 'outputs' or 'error' fields upon completion.
    """

    sub_task_id: str = Field(default_factory=lambda: f"sub-{uuid.uuid4().hex[:8]}", description="The unique identifier for this specific sub-task node.")

    title: str = Field(description="A clear, human-readable description of the work to be done.")

    assigned_agent: str = Field(description="The specific role or name of the agent responsible for execution (e.g., 'WebScraperAgent').")

    status: TaskStatus = Field(default=TaskStatus.PENDING, description="The current operational state of this sub-task.")

    dependencies: List[str] = Field(default_factory=list, description="A list of 'sub_task_id' strings that must be marked COMPLETED before this task can start.")

    inputs: Dict[str, Any] = Field(default_factory=dict, description="The specific parameters, targets, or templates required by the agent to begin work.")

    outputs: Dict[str, Any] = Field(default_factory=dict, description="The resulting artifacts, parsed data, or status messages generated by the agent upon completion.")

    error: Optional[str] = Field(default=None, description="Captures exception messages or tracebacks if the status switches to FAILED.")


class TaskState(BaseModel):
    """Represents the overarching global workflow and acts as the container for the DAG.

    This object is serialized to the storage layer, allowing the orchestration
    engine to maintain state awareness across disparate agent executions.
    """

    task_id: str = Field(description="The globally unique identifier for this entire workflow execution.")

    global_goal: str = Field(description="The primary objective or final output the multi-agent system is trying to achieve.")

    status: TaskStatus = Field(default=TaskStatus.RUNNING, description="The aggregate status of the overarching task. Switches to COMPLETED when all sub-tasks are done.")

    context_data: Dict[str, Any] = Field(default_factory=dict, description="Global environment variables, shared configurations, or user constraints available to all sub-tasks.")

    sub_tasks: List[SubTaskState] = Field(default_factory=list, description="The active list of all sub-tasks (the DAG) associated with this global goal.")

    updated_at: float = Field(
        default_factory=lambda: datetime.now(timezone.utc).timestamp(), description="The high-precision UTC Unix epoch timestamp recording the last time this state was modified."
    )
